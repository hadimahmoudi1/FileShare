( NAME = N'TU', FILENAME = N'c:\TUData\TU.mdf' , SIZE = 20480KB , MAXSIZE = UNLIMITED, FILEGROWTH = 30% )
 LOG ON 
( NAME = N'TU_log', FILENAME = N'c:\TUData\TU_log.ldf' , SIZE = 26752KB , MAXSIZE = 2048GB , FILEGROWTH = 30%)
GO

